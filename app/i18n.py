"""Traducciones de la interfaz (español por defecto, inglés opcional).

El idioma se guarda en ``[app].language`` y se aplica al arrancar. Los textos
del motor (errores de conversion) se mantienen en español por ahora; la UI
completa usa :func:`tr`.
"""

from __future__ import annotations

LANGUAGES: tuple[str, ...] = ("es", "en")
DEFAULT_LANGUAGE = "es"
LANGUAGE_LABELS = {"es": "Español", "en": "English"}

_CURRENT = {"language": DEFAULT_LANGUAGE}


def set_language(language: str) -> str:
    """Fija el idioma global y devuelve el valor efectivo."""
    value = str(language).strip().lower()
    _CURRENT["language"] = value if value in LANGUAGES else DEFAULT_LANGUAGE
    return _CURRENT["language"]


def current_language() -> str:
    return _CURRENT["language"]


class _SafeValues(dict):
    """Diccionario que deja intactos los marcadores que no se han pasado."""

    def __missing__(self, key: str) -> str:
        return "{" + key + "}"


def tr(key: str, **values: object) -> str:
    """Devuelve el texto traducido del idioma activo.

    Los marcadores sin valor se conservan tal cual (``{size}``) en lugar de
    romper el texto entero.
    """
    text = _TEXTS.get(_CURRENT["language"], _TEXTS[DEFAULT_LANGUAGE]).get(key)
    if text is None:
        text = _TEXTS[DEFAULT_LANGUAGE].get(key, key)
    try:
        return text.format_map(_SafeValues(values))
    except (IndexError, ValueError):
        return text


